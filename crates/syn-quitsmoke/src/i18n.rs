//! Переводы QuitSmoke — схема synshell: исходные строки русские (`n_!` — их собирает
//! `syngui/scripts/i18n-extract.py`), переводы — каталоги `i18n/<язык>.lang`. Экраны
//! по-прежнему обращаются к строкам по ключам (`state.tr("nav.home")`, ключи вех и
//! достижений собираются на лету); ключ → исходная строка → перевод текущего языка.

use std::collections::HashMap;
use std::sync::{Mutex, OnceLock};

use syngui::n_;

use crate::model::settings::Locale;

/// Подключить каталоги и выбрать язык (вызвать один раз при старте).
pub fn init(locale: Locale) {
    syngui::i18n::set_source_language("ru");
    syngui::i18n::register_catalogs(&synshell_tr::catalogs!("../i18n"));
    apply(locale);
}

/// Язык интерфейса по настройке приложения.
pub fn apply(locale: Locale) {
    syngui::i18n::set_language(match locale {
        Locale::Ru => "ru",
        Locale::En => "en",
    });
}

/// Перевести ключ. Неизвестный ключ → пустая строка (заметно при отладке). Перевод
/// закрепляется на пару «язык + ключ» (строк конечное число — память не растёт).
pub fn t(key: &str, _locale: Locale) -> &'static str {
    let Some(s) = source(key) else { return "" };
    static CACHE: OnceLock<Mutex<HashMap<(String, &'static str), &'static str>>> = OnceLock::new();
    let lang = syngui::i18n::language().tag().to_string();
    let mut c = CACHE.get_or_init(Default::default).lock().unwrap();
    *c.entry((lang, s)).or_insert_with(|| Box::leak(syngui::i18n::t(s).into_boxed_str()))
}

