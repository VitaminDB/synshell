fn map() -> &'static HashMap<String, &'static str> {
    static M: OnceLock<HashMap<String, &'static str>> = OnceLock::new();
    M.get_or_init(|| {
        WORDS
            .iter()
            .filter(|w| w.contains('ё'))
            .map(|w| (w.replace('ё', "е"), *w))
            .filter(|(e, w)| e != *w)
            .collect()
    })
}

/// Поставить «ё» в однозначных русских словах текста.
pub fn yofy(text: &str) -> String {
    if !text.chars().any(|c| matches!(c, 'е' | 'Е')) {
        return text.to_string();
    }
    let m = map();
    let mut out = String::with_capacity(text.len() + 8);
    let mut word = String::new();
    let flush = |word: &mut String, out: &mut String| {
        if word.is_empty() {
            return;
        }
        let low = word.to_lowercase();
        match m.get(&low) {
            Some(yo) => {
                // регистр: каждая буква как была (Ещё, ЕЩЁ)
                for (orig, new) in word.chars().zip(yo.chars()) {
                    if orig.is_uppercase() {
                        out.extend(new.to_uppercase());
                    } else {
                        out.push(new);
                    }
                }
            }
            None => out.push_str(word),
        }
        word.clear();
    };
    for c in text.chars() {
        if c.is_alphabetic() || (c == '-' && !word.is_empty()) {
            word.push(c);
        } else {
            flush(&mut word, &mut out);
            out.push(c);
        }
    }
    flush(&mut word, &mut out);
    out
}

/// «ё» во всех строках JSON-значения (параметры рецепта).
pub fn yofy_value(v: &mut serde_json::Value) {
    match v {
        // пути к файлам не трогаем
        serde_json::Value::String(s) if s.starts_with('/') || s.starts_with('~') || (s.contains('/') && !s.contains(' ')) => {}
        serde_json::Value::String(s) => {
            let y = yofy(s);
            if y != *s {
                *s = y;
            }
        }
        serde_json::Value::Array(a) => a.iter_mut().for_each(yofy_value),
        serde_json::Value::Object(o) => o.values_mut().for_each(yofy_value),
        _ => {}
    }
}

#[cfg(test)]
mod tests {
    use super::yofy;

    #[test]
    fn yo() {
        assert_eq!(yofy("Еще немного, и пойдем! Котел черный."), "Ещё немного, и пойдём! Котёл чёрный.");
        assert_eq!(yofy("ЕЩЕ"), "ЕЩЁ");
        // неоднозначные не трогаем
        assert_eq!(yofy("Все готово, небо синее"), "Все готово, небо синее");
        // английский и пути — как были
        assert_eq!(yofy("Krya says: «Где он? Идет!»"), "Krya says: «Где он? Идёт!»");
        let mut v = serde_json::json!({"story": "«Еще!»", "refs": ["/tmp/еще.png"]});
        super::yofy_value(&mut v);
        assert_eq!(v, serde_json::json!({"story": "«Ещё!»", "refs": ["/tmp/еще.png"]}));
    }
}
